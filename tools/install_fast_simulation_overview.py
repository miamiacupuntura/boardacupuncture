#!/usr/bin/env python3
"""Extend published preparation to overview without bypassing its audit inventory."""
import install_fast_published_attempts as base
original_patch=base.patch

def patch(source):
    marker='// Published overview fast preparation v1'
    if marker in source:return source
    source=original_patch(source)
    if '// Published snapshot student inventory v1' not in source:
        raise RuntimeError('Falta el selector de versiones publicadas; no se cambió nada.')
    old="if (in_array($track, ['exams', 'simulation'], true) && $mixdomains) {\n    require_once(__DIR__ . '/../myprogress/herbology-published-attempt-fast.php');"
    new="// Published overview fast preparation v1\nif (in_array($track, ['exams', 'simulation'], true)) {\n    require_once(__DIR__ . '/../myprogress/herbology-published-attempt-fast.php');"
    if source.count(old)!=1:raise RuntimeError('No se identificó la carga publicada.')
    source=source.replace(old,new,1)
    old="if ($exammode === 'officialadaptive' || (int)$fastnumber === $attemptselectednumber) {"
    if source.count(old)!=1:raise RuntimeError('No se identificó la preparación del texto.')
    source=source.replace(old,"if (!$mixdomains || $exammode === 'officialadaptive' || (int)$fastnumber === $attemptselectednumber) {",1)
    old="if (!$fastpublishedattempt) {\n$mockcategorydefinitions = ["
    if source.count(old)!=1:raise RuntimeError('No se identificó el inventario auxiliar.')
    source=source.replace(old,"if (!$fastpublishedattempt || !$mixdomains) {\n$mockexcludedquestionids = [];\nif (!$fastpublishedattempt) {\n$mockcategorydefinitions = [",1)
    anchor='// Student-facing Bensky coverage uses the cached classification generated by'
    if source.count(anchor)!=1:raise RuntimeError('No se identificó el inventario del alumno.')
    source=source.replace(anchor,'}\n\n'+anchor,1)
    anchor='// Individual-herb Mock questions are also indexed by the broader Yang chapter'
    if source.count(anchor)!=1:raise RuntimeError('No se identificó el inventario de capítulos.')
    source=source.replace(anchor,'if (!$fastpublishedattempt) {\n'+anchor,1)
    anchor="if ($fastpublishedattempt && !headers_sent()) {"
    if source.count(anchor)!=1:raise RuntimeError('No se identificó el final del inventario.')
    source=source.replace(anchor,'}\n'+anchor,1)
    return source

if __name__=='__main__':
    base.patch=patch
    # Keep original callable for installations predating the Begin optimization.
    base.main()
